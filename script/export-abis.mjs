#!/usr/bin/env node
// Writes frontend/src/lib/abi/launchpad.ts from Foundry artifacts.
// Uses the implementation artifact when it has been built and falls back to the interface otherwise.
//
//   forge build && node script/export-abis.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "out");
const target = join(root, "frontend/src/lib/abi/launchpad.ts");

const exportsSpec = [
  ["dprkPassAbi", ["DprkPass.sol/DprkPass.json", "IDprkPass.sol/IDprkPass.json"]],
  ["dprkLaunchpadAbi", ["DprkLaunchpad.sol/DprkLaunchpad.json", "IDprkLaunchpad.sol/IDprkLaunchpad.json"]],
  ["dprkTokenAbi", ["DprkToken.sol/DprkToken.json", "IDprkToken.sol/IDprkToken.json"]],
];

let body = "// Generated by script/export-abis.mjs from Foundry artifacts. Do not edit by hand.\n";
for (const [name, candidates] of exportsSpec) {
  const found = candidates.find((rel) => existsSync(join(outDir, rel)));
  if (!found) {
    console.error(`missing artifact for ${name}: run \`forge build\` first (looked for ${candidates.join(", ")})`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(join(outDir, found), "utf8"));
  body += `\n// source: out/${found}\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  console.log(`${name} <- out/${found} (${abi.length} entries)`);
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, body);
console.log(`wrote ${target}`);
